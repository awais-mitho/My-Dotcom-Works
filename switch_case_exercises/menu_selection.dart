void main() {
  int choice = 2;

  switch (choice) {
    case 1:
      print("Burger");
      break;

    case 2:
      print("Pizza");
      break;

    case 3:
      print("Biryani");
      break;

    case 4:
      print("Sandwich");
      break;

    default:
      print("Invalid choice");
  }
}